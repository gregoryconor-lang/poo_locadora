        Cliente meuCliente = new Cliente();
        
        // Definir os valores dos atributos a partir do formulário
        meuCliente.setNome(txtNome.getText());
        meuCliente.setTelefone(txtTelefone.getText());
        meuCliente.setCpf(txtCpf.getText());

        // Instanciar um objeto da classe ClienteDAO
        ClienteDAO dao = new ClienteDAO();
        dao.create(meuCliente);
        
        limpar();
