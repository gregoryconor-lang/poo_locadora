    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        meuFilme = new Filme();
        meuFilme.setTitulo(txtTitulo.getText());
        meuFilme.setDuracao(Integer.parseInt(txtDuracao.getText()));
        meuFilme.setSinopse(txtSinopse.getText());
        
        FilmeDAO dao = new FilmeDAO();
        dao.create(meuFilme);
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void tblCadastradosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCadastradosMouseClicked
        int linha = tblCadastrados.getSelectedRow();
        
        if(linha != -1) {
            String id = tblCadastrados.getValueAt(linha, 0).toString();
            FilmeDAO dao = new FilmeDAO();
            
            meuFilme = dao.read(Integer.parseInt(id));
            
            txtTitulo.setText(meuFilme.getTitulo());
            txtDuracao.setText(String.valueOf(meuFilme.getDuracao()));
            txtSinopse.setText(meuFilme.getSinopse());
            
            btnSalvar.setEnabled(false);
            btnEditar.setEnabled(true);
            btnExcluir.setEnabled(true);
        }
    }//GEN-LAST:event_tblCadastradosMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        meuFilme.setTitulo(txtTitulo.getText());
        meuFilme.setDuracao(Integer.parseInt(txtDuracao.getText()));
        meuFilme.setSinopse(txtSinopse.getText());
        
        FilmeDAO dao = new FilmeDAO();
        dao.update(meuFilme);
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int opcao = JOptionPane.showConfirmDialog(null, "Tem certeza que deseja excluir este Filme?");
        
        if(opcao == JOptionPane.YES_OPTION) {
            FilmeDAO dao = new FilmeDAO();
            dao.destroy(meuFilme);
            
            // Limpar o form e atualizar a tabela
            limpar();
            preencherTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed


